const i18n = {
  currentLang: localStorage.getItem('portfolio-lang') || 'fr',

  t(key) {
    return translations[this.currentLang][key] || translations['fr'][key] || key;
  },

  setLang(lang) {
    this.currentLang = lang;
    localStorage.setItem('portfolio-lang', lang);
    this.applyTranslations();
    this.updateLangButton();
    document.documentElement.lang = lang;
  },

  applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val) {
        if (el.tagName === 'INPUT' && el.getAttribute('placeholder') !== null) {
          el.setAttribute('placeholder', val);
        } else {
          el.innerHTML = val;
        }
      }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', this.t(key));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.setAttribute('title', this.t(key));
    });
  },

  updateLangButton() {
    const btn = document.getElementById('lang-toggle');
    if (!btn) return;
    if (this.currentLang === 'fr') {
      btn.innerHTML = '<span class="lang-flag">🇬🇧</span><span class="lang-label">EN</span>';
      btn.setAttribute('title', 'Switch to English');
    } else {
      btn.innerHTML = '<span class="lang-flag">🇫🇷</span><span class="lang-label">FR</span>';
      btn.setAttribute('title', 'Passer en français');
    }
  },

  init() {
    this.applyTranslations();
    this.updateLangButton();

    const btn = document.getElementById('lang-toggle');
    if (btn) {
      btn.addEventListener('click', () => {
        this.setLang(this.currentLang === 'fr' ? 'en' : 'fr');
      });
    }
  }
};

document.addEventListener('DOMContentLoaded', () => i18n.init());
